// Function to search skills with fuzzy matching
export const searchSkills = (query: string, skills: string[] = ALL_SKILLS, maxResults: number = 10): string[] => {
  if (!query.trim()) return []

  const normalizedQuery = query.toLowerCase().trim()

  // Exact matches first
  const exactMatches = skills.filter(skill =>
    skill.toLowerCase() === normalizedQuery
  )

  // Starts with matches
  const startsWithMatches = skills.filter(skill =>
    skill.toLowerCase().startsWith(normalizedQuery) &&
    !exactMatches.includes(skill)
  )

  // Contains matches
  const containsMatches = skills.filter(skill =>
    skill.toLowerCase().includes(normalizedQuery) &&
    !exactMatches.includes(skill) &&
    !startsWithMatches.includes(skill)
  )

  // Word boundary matches
  const wordMatches = skills.filter(skill => {
    const words = skill.toLowerCase().split(/\s+/)
    return words.some(word => word.startsWith(normalizedQuery)) &&
           !exactMatches.includes(skill) &&
           !startsWithMatches.includes(skill) &&
           !containsMatches.includes(skill)
  })

  // Fuzzy matches (simple edit distance)
  const fuzzyMatches = skills.filter(skill => {
    const skillLower = skill.toLowerCase()
    const distance = levenshteinDistance(normalizedQuery, skillLower)
    return distance <= 2 && distance > 0 &&
           !exactMatches.includes(skill) &&
           !startsWithMatches.includes(skill) &&
           !containsMatches.includes(skill) &&
           !wordMatches.includes(skill)
  }).sort((a, b) => {
    const distanceA = levenshteinDistance(normalizedQuery, a.toLowerCase())
    const distanceB = levenshteinDistance(normalizedQuery, b.toLowerCase())
    return distanceA - distanceB
  })

  const allMatches = [
    ...exactMatches,
    ...startsWithMatches,
    ...containsMatches,
    ...wordMatches,
    ...fuzzyMatches
  ]

  return allMatches.slice(0, maxResults)
}

// Simple Levenshtein distance implementation for fuzzy matching
function levenshteinDistance(str1: string, str2: string): number {
  const matrix = []

  for (let i = 0; i <= str2.length; i++) {
    matrix[i] = [i]
  }

  for (let j = 0; j <= str1.length; j++) {
    matrix[0][j] = j
  }

  for (let i = 1; i <= str2.length; i++) {
    for (let j = 1; j <= str1.length; j++) {
      if (str2.charAt(i - 1) === str1.charAt(j - 1)) {
        matrix[i][j] = matrix[i - 1][j - 1]
      } else {
        matrix[i][j] = Math.min(
          matrix[i - 1][j - 1] + 1,
          matrix[i][j - 1] + 1,
          matrix[i - 1][j] + 1
        )
      }
    }
  }

  return matrix[str2.length][str1.length]
}
